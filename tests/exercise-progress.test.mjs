import assert from 'node:assert/strict';
import {progressKey,saveProgress,loadProgress,clearProgress} from '../exercise-progress.mjs';
const memory=new Map(),storage={getItem:k=>memory.get(k)??null,setItem:(k,v)=>memory.set(k,v),removeItem:k=>memory.delete(k)};
const exercise={title:'练习',questions:Array.from({length:30},(_,i)=>({id:i+1,type:i%2?'fill':'choice',text:'题目'+i}))};
const key=progressKey('An','hsk3','1');
const answers=Object.fromEntries(exercise.questions.map((q,i)=>[q.id,i<19?(q.type==='choice'?'B':'你好'):'']));
assert.equal(saveProgress(key,exercise,answers,{index:19,offset:-24},storage),true);
const resumed=loadProgress(key,structuredClone(exercise),storage);
assert.deepEqual(resumed,{answers,position:{index:19,offset:-24}});
assert.equal(loadProgress(progressKey('Lan','hsk3','1'),exercise,storage),null);
assert.equal(loadProgress(progressKey('An','hsk4','1'),exercise,storage),null);
assert.equal(loadProgress(progressKey('An','hsk3','2'),exercise,storage),null);
const changed=structuredClone(exercise);changed.questions[0].text='新题';
assert.equal(loadProgress(key,changed,storage),null);
assert.equal(clearProgress(key,storage),true);
assert.equal(loadProgress(key,exercise,storage),null);
storage.setItem(key,'broken');assert.equal(loadProgress(key,exercise,storage),null);
saveProgress(key,exercise,{1:'Z',2:'未完成的填空'},{index:999,offset:0},storage);
assert.deepEqual(loadProgress(key,exercise,storage),{answers:{...Object.fromEntries(exercise.questions.map(q=>[q.id,''])),2:'未完成的填空'},position:{index:0,offset:0}});
const blocked={getItem(){throw Error();},setItem(){throw Error();},removeItem(){throw Error();}};
assert.equal(loadProgress(key,exercise,blocked),null);
assert.equal(saveProgress(key,exercise,answers,{},blocked),false);
assert.equal(clearProgress(key,blocked),false);
console.log('Exercise progress tests passed');
